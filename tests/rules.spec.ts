import {test,expect} from '@playwright/test';
test('rules sections, numbered search, bilingual reader, original figures and bookmarks work offline',async({page})=>{
  const remote:string[]=[];page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:5185')&&!r.url().startsWith('data:'))remote.push(r.url());});
  await page.goto('/#rules');
  await expect(page.locator('.rule-section-card')).toHaveCount(12);
  await expect(page.locator('.rule-card')).toHaveCount(0);
  await page.locator('.rule-section-card').filter({hasText:'比赛规则'}).click();
  await expect(page).toHaveURL(/#rules\/section-game$/);
  await expect(page.locator('.rule-card')).toHaveCount(0);
  await expect(page.locator('.rule-category-card')).toHaveCount(5);
  await page.locator('.rule-category-card').filter({hasText:'得分判定'}).click();
  await expect(page.locator('.rule-card')).toHaveCount(8);
  await page.reload();
  await expect(page.locator('.rule-card')).toHaveCount(8);
  await expect(page.locator('.rule-card')).not.toContainText(['SG1']);
  await page.locator('.rule-section-nav').getByRole('button',{name:'机器人与检录',exact:true}).click();
  await expect(page.locator('.rule-category-card')).toHaveCount(1);
  await page.locator('.rule-category-card').click();
  await expect(page.locator('.rule-card')).toHaveCount(28);
  await page.locator('.rule-section-nav').getByRole('button',{name:'全部分区',exact:true}).click();
  await expect(page.locator('.rule-section-card')).toHaveCount(12);
  await page.getByRole('textbox',{name:'搜索赛事规则'}).fill('SG1');
  await page.locator('.rule-card').filter({hasText:'开赛摆放条件'}).click();
  await expect(page.locator('.rule-text')).toContainText('457.2');
  await page.getByRole('button',{name:'对照',exact:true}).click();
  await expect(page.locator('.rule-columns.dual article')).toHaveCount(2);
  await expect(page.locator('.rule-text[lang=en]')).toContainText('Starting a Match');
  await page.getByRole('button',{name:'收藏规则',exact:true}).click();
  await page.reload();
  await expect(page.getByRole('button',{name:'收藏规则',exact:true})).toHaveAttribute('aria-pressed','true');
  await page.getByRole('button',{name:'查看官方原页与配图'}).click();
  await expect(page.locator('.rule-original-pages img').first()).toBeVisible();
  expect(await page.locator('.rule-original-pages img').first().evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBeTruthy();
  await page.screenshot({path:'screenshots/rules-bilingual.png'});
  await page.getByRole('button',{name:'EN',exact:true}).click();
  await expect(page.locator('.rule-text[lang=en]')).toContainText('Starting a Match');
  await page.goto('/#rules');
  await page.getByRole('button',{name:/Bookmarks ·/}).click();
  await expect(page.locator('.rule-card')).toHaveCount(1);
  expect(remote).toEqual([]);
});

test('section links, reader breadcrumbs and narrow layouts retain the hierarchy',async({page})=>{
  await page.goto('/#rules/section-game~SG');
  await expect(page.locator('.rule-card')).toHaveCount(13);
  await page.locator('.rule-card').filter({hasText:'开赛摆放条件'}).click();
  await page.getByRole('button',{name:'返回所属分区'}).click();
  await expect(page).toHaveURL(/#rules\/section-game~SG$/);
  await expect(page.locator('.rule-card')).toHaveCount(13);
  await page.goBack();
  await expect(page.locator('.rule-columns')).toBeVisible();
  await page.locator('.rules-breadcrumb').getByRole('button',{name:'比赛规则',exact:true}).click();
  await expect(page.locator('.rule-category-card')).toHaveCount(5);
  await page.setViewportSize({width:960,height:760});
  await page.screenshot({path:'screenshots/rules-section-narrow.png'});
  expect(await page.locator('.rules-main').evaluate(el=>el.scrollWidth<=el.clientWidth+1)).toBeTruthy();
  await page.goto('/#rules/section-not-found');
  await expect(page.getByRole('heading',{name:'未找到这个规则分区'})).toBeVisible();
});
